#!/usr/bin/env python3
"""Generate static /game-detail/<slug>/index.html stubs and sitemap.xml.

GitHub Pages has no path rewrites, so each game needs a real file in order
for /game-detail/<slug> to return HTTP 200. This script copies game-detail.html,
injects a per-game <title> and <link rel="canonical">, and rebuilds sitemap.xml.

Re-run from the site repo root (or any cwd; the repo root is detected)
whenever games are added or game-detail.html changes:

    python3 scripts/gen-slug-pages.py

Reads the public catalog with the same anon/publishable key the site already
uses. Slug policy (must match assets/js/hive-slugs.js and the SQL migration):
  * use games.slug when present
  * otherwise a non-UUID id, or slugify(title) for UUID ids
"""
from __future__ import annotations

import json
import re
import sys
import urllib.error
import urllib.request
from html import escape
from pathlib import Path

SUPABASE_URL = "https://tskbfytfjsiavwysecuk.supabase.co"
SITE_ORIGIN = "https://homebrewhive.com"
# Fallback only if the key cannot be read from game-detail.html.
DEFAULT_ANON_KEY = "sb_publishable_I27CpcilWluOjUSSb6y_pQ_t9ylEjmB"
UUID_RE = re.compile(
    r"^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$",
    re.I,
)
GENERATED_MARK = "Generated by scripts/gen-slug-pages.py"
KEY_RE = re.compile(r"const SUPABASE_KEY = '([^']+)'")
URL_RE = re.compile(r"const SUPABASE_URL = '([^']+)'")

STATIC_SITEMAP_PAGES = [
    (f"{SITE_ORIGIN}/", "weekly", "1.0"),
    (f"{SITE_ORIGIN}/games.html", "daily", "0.9"),
    (f"{SITE_ORIGIN}/how-it-works.html", "monthly", "0.6"),
    (f"{SITE_ORIGIN}/find-us.html", "monthly", "0.5"),
    (f"{SITE_ORIGIN}/request-us.html", "monthly", "0.5"),
    (f"{SITE_ORIGIN}/contact-us.html", "monthly", "0.4"),
    (f"{SITE_ORIGIN}/build-your-own-game.html", "monthly", "0.4"),
    (f"{SITE_ORIGIN}/sticker.html", "monthly", "0.4"),
    (f"{SITE_ORIGIN}/rules.html", "yearly", "0.3"),
]


def repo_root() -> Path:
    here = Path(__file__).resolve().parent
    for candidate in (here.parent, Path.cwd()):
        if (candidate / "game-detail.html").is_file():
            return candidate
    raise SystemExit("Could not find game-detail.html (run from the site repo).")


def slugify(title: str) -> str:
    s = (title or "").lower()
    s = re.sub(r"[^a-z0-9]+", "-", s)
    s = re.sub(r"-+", "-", s)
    return s.strip("-")


def is_uuid(value: str) -> bool:
    return bool(UUID_RE.match(value or ""))


def canonical_slug(game: dict) -> str:
    slug = (game.get("slug") or "").strip()
    if slug:
        return slug
    game_id = (game.get("id") or "").strip()
    if game_id and not is_uuid(game_id):
        return game_id
    return slugify(game.get("title") or "")


def read_credentials(template: str) -> tuple[str, str]:
    url_m = URL_RE.search(template)
    key_m = KEY_RE.search(template)
    url = url_m.group(1) if url_m else SUPABASE_URL
    key = key_m.group(1) if key_m else DEFAULT_ANON_KEY
    return url, key


def fetch_games(url: str, key: str) -> list[dict]:
    endpoint = url.rstrip("/") + "/rest/v1/games?select=id,title,slug,status,sort_order&order=sort_order.asc.nullslast,title.asc"
    req = urllib.request.Request(
        endpoint,
        headers={
            "apikey": key,
            "Authorization": "Bearer " + key,
            "Accept": "application/json",
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            data = json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        body = exc.read().decode("utf-8", "replace")
        raise SystemExit(f"Supabase request failed: {exc.code} {body}") from exc
    if not isinstance(data, list):
        raise SystemExit(f"Unexpected Supabase response: {data!r}")
    return data


def apply_template(template: str, title: str, slug: str) -> str:
    canonical = f"{SITE_ORIGIN}/game-detail/{slug}"
    html = template
    if GENERATED_MARK not in html:
        html = html.replace(
            "<head>",
            "<head>\n  <!-- " + GENERATED_MARK + ". Do not edit by hand. -->",
            1,
        )
    title_html = escape(title, quote=True)
    canonical_html = escape(canonical, quote=True)
    if "<title>" not in html:
        raise SystemExit("game-detail.html is missing a <title> tag")
    html = re.sub(
        r"<title>.*?</title>",
        f"<title>{title_html} - Homebrew Hive</title>",
        html,
        count=1,
        flags=re.S,
    )
    canonical_tag = f'<link rel="canonical" href="{canonical_html}">'
    if re.search(r'<link\s+rel="canonical"', html, flags=re.I):
        html = re.sub(
            r'<link\s+rel="canonical"[^>]*>',
            canonical_tag,
            html,
            count=1,
            flags=re.I,
        )
    else:
        html = html.replace("</title>", "</title>\n  " + canonical_tag, 1)
    return html


def is_generated_dir(path: Path) -> bool:
    index = path / "index.html"
    if not index.is_file():
        return False
    text = index.read_text(encoding="utf-8")
    return GENERATED_MARK in text


def write_stubs(root: Path, template: str, games: list[dict]) -> list[str]:
    dest_root = root / "game-detail"
    dest_root.mkdir(exist_ok=True)
    written = []
    wanted = set()
    for game in games:
        slug = canonical_slug(game)
        title = game.get("title") or slug
        if not slug:
            print(f"skip row with no slug: id={game.get('id')!r} title={title!r}", file=sys.stderr)
            continue
        if "/" in slug or slug in {".", ".."}:
            raise SystemExit(f"Refusing unsafe slug: {slug!r}")
        wanted.add(slug)
        folder = dest_root / slug
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "index.html").write_text(apply_template(template, title, slug), encoding="utf-8")
        written.append(slug)

    # Remove stale generated stubs only (leave anything handmade alone).
    if dest_root.is_dir():
        for child in dest_root.iterdir():
            if child.is_dir() and child.name not in wanted and is_generated_dir(child):
                (child / "index.html").unlink()
                try:
                    child.rmdir()
                except OSError:
                    pass
                print(f"removed stale stub: game-detail/{child.name}/")
    return written


def is_listed(game: dict) -> bool:
    status = game.get("status")
    return status == "Approved" or status is None


def write_sitemap(root: Path, games: list[dict]) -> int:
    urls = []
    for loc, freq, pri in STATIC_SITEMAP_PAGES:
        urls.append(
            "  <url>\n"
            f"    <loc>{escape(loc, quote=True)}</loc>\n"
            f"    <changefreq>{freq}</changefreq>\n"
            f"    <priority>{pri}</priority>\n"
            "  </url>"
        )
    listed = 0
    for game in games:
        if not is_listed(game):
            continue
        slug = canonical_slug(game)
        if not slug:
            continue
        loc = f"{SITE_ORIGIN}/game-detail/{slug}"
        urls.append(
            "  <url>\n"
            f"    <loc>{escape(loc, quote=True)}</loc>\n"
            "    <changefreq>weekly</changefreq>\n"
            "    <priority>0.8</priority>\n"
            "  </url>"
        )
        listed += 1
    text = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
        + "\n".join(urls)
        + "\n</urlset>\n"
    )
    (root / "sitemap.xml").write_text(text, encoding="utf-8")
    return listed


def main() -> None:
    root = repo_root()
    template_path = root / "game-detail.html"
    template = template_path.read_text(encoding="utf-8")
    url, key = read_credentials(template)
    games = fetch_games(url, key)
    slugs = write_stubs(root, template, games)
    sitemap_games = write_sitemap(root, games)
    print(f"Wrote {len(slugs)} stub(s) under game-detail/<slug>/index.html")
    print(f"Wrote sitemap.xml with {sitemap_games} game URL(s)")
    missing = [canonical_slug(g) or g.get("id") for g in games if not canonical_slug(g)]
    if missing:
        raise SystemExit(f"Some rows had no usable slug: {missing}")


if __name__ == "__main__":
    main()
